export function vaccineStatus(dose: VaccineDose, ageDays: number | null): 'due' | 'upcoming' | 'later' | 'passed' {
  if (ageDays == null) return 'later';
  if (ageDays < dose.dayFrom - 7) return 'later';
  if (ageDays < dose.dayFrom) return 'upcoming';
  if (ageDays <= dose.dayTo + 14) return 'due';
  return 'passed';
}
